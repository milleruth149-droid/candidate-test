// namespace = "הכתובת" של הקובץ. זהה לקובץ הקודם, כדי שהקבצים יכירו זה את זה.
namespace Requests.Application.Requests;

// הקובץ הזה מגדיר איך נראית "תשובה של חיפוש".
// במקום להחזיר את כל הרשומות, נחזיר רק עמוד אחד, יחד עם מידע על העימוד.
//
// ה-<T> אחרי השם אומר "סוג כלשהו, נקבע בהמשך".
// עכשיו נשתמש בו עם RequestDto, ובעתיד אפשר להשתמש בו עם כל סוג אחר.
public sealed record PagedResult<T>(

    // הרשומות של העמוד הנוכחי בלבד (למשל 20 רשומות).
    IReadOnlyList<T> Items,

    // מספר העמוד הנוכחי (מתחיל מ-1).
    int Page,

    // כמה רשומות יש בעמוד.
    int PageSize,

    // כמה רשומות יש בסך הכל שמתאימות לחיפוש (לא רק בעמוד הזה).
    // ה-Angular צריך את המספר הזה כדי לחשב כמה עמודים להציג.
    int TotalCount);


    //מזה ה-Angular יידע להציג "עמוד 1 מתוך 50".